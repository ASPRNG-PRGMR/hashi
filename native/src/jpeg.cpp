std::array<std::uint8_t, 64> scale_qtable(
    const std::array<std::uint16_t, 64>& base, int quality) {
  if (quality < 1 || quality > 100) {
    throw ProtocolError("quality must be 1..100, got " +
                        std::to_string(quality));
  }
  // The standard IJG scaling formula. At quality 80 this is an exact match for
  // the captured tables on all 64 coefficients of both.
  const int scale = quality < 50 ? 5000 / quality : 200 - 2 * quality;
  std::array<std::uint8_t, 64> out{};
  for (std::size_t i = 0; i < 64; ++i) {
    const int value = (static_cast<int>(base[i]) * scale + 50) / 100;
    out[i] = static_cast<std::uint8_t>(std::clamp(value, 1, 255));
  }
  return out;
}

namespace {

Bytes segment(std::uint8_t marker, const Bytes& body) {
  Bytes out;
  out.push_back(0xFF);
  out.push_back(marker);
  put_be16(out, static_cast<std::uint16_t>(body.size() + 2));
  append(out, body);
  return out;
}

}  // namespace

Bytes build_dqt(const std::array<std::uint16_t, 64>& base, int table_id,
                int quality) {
  if (table_id != 0 && table_id != 1) {
    throw ProtocolError("table_id must be 0 or 1, got " +
                        std::to_string(table_id));
  }
  const auto scaled = scale_qtable(base, quality);
  Bytes body;
  body.push_back(static_cast<std::uint8_t>(table_id));
  for (std::size_t i = 0; i < 64; ++i) body.push_back(scaled[kZigzag[i]]);
  return segment(0xDB, body);
}

Bytes build_dht(int table_class, int table_id, const std::uint8_t* counts,
                std::size_t counts_len, const std::uint8_t* values,
                std::size_t values_len) {
  std::size_t total = 0;
  for (std::size_t i = 0; i < counts_len; ++i) total += counts[i];
  if (total != values_len) {
    throw ProtocolError("counts sum " + std::to_string(total) + " != " +
                        std::to_string(values_len) + " values");
  }
  Bytes body;
  body.push_back(static_cast<std::uint8_t>((table_class << 4) | table_id));
  body.insert(body.end(), counts, counts + counts_len);
  body.insert(body.end(), values, values + values_len);
  return segment(0xC4, body);
}

Bytes build_sof0(int width, int height) {
  if (width < 1 || width > 0xFFFF || height < 1 || height > 0xFFFF) {
    throw ProtocolError("invalid dimensions " + std::to_string(width) + "x" +
                        std::to_string(height));
  }
  Bytes body;
  body.push_back(8);  // sample precision
  put_be16(body, static_cast<std::uint16_t>(height));
  put_be16(body, static_cast<std::uint16_t>(width));
  body.push_back(3);  // three components
  // Sampling factors 0x22 / 0x11 / 0x11 are 4:2:0; selectors 0, 1, 1.
  body.insert(body.end(), {1, 0x22, 0,
                           2, 0x11, 1,
                           3, 0x11, 1});
  return segment(0xC0, body);
}

Bytes build_app0(int density) {
  if (density < 1 || density > 0xFFFF) {
    throw ProtocolError("invalid density " + std::to_string(density));
  }
  Bytes body;
  append(body, std::string("JFIF"));
  body.push_back(0x00);
  body.insert(body.end(), {1, 1, 1});  // version 1.01, units = 1 (dpi)
  put_be16(body, static_cast<std::uint16_t>(density));
  put_be16(body, static_cast<std::uint16_t>(density));
  body.insert(body.end(), {0, 0});  // no thumbnail
  return segment(0xE0, body);
}

Bytes build_sos() {
  const Bytes body{3, 1, 0x00, 2, 0x11, 3, 0x11, 0, 0x3F, 0};
  return segment(0xDA, body);
}

Bytes build_prelude(int width, int height, int quality, int density) {
  Bytes out{0xFF, 0xD8};  // SOI
  append(out, build_app0(density));
  append(out, build_dqt(kBaseLumaQTable, 0, quality));
  append(out, build_dqt(kBaseChromaQTable, 1, quality));
  append(out, build_sof0(width, height));
  append(out, build_dht(0, 0, kDcLumaCounts.data(), kDcLumaCounts.size(),
                        kDcLumaValues.data(), kDcLumaValues.size()));
  append(out, build_dht(1, 0, kAcLumaCounts.data(), kAcLumaCounts.size(),
                        kAcLumaValues.data(), kAcLumaValues.size()));
  append(out, build_dht(0, 1, kDcChromaCounts.data(), kDcChromaCounts.size(),
                        kDcChromaValues.data(), kDcChromaValues.size()));
  append(out, build_dht(1, 1, kAcChromaCounts.data(), kAcChromaCounts.size(),
                        kAcChromaValues.data(), kAcChromaValues.size()));
  append(out, build_sos());
  return out;
}

std::vector<Segment> parse_segments(const std::uint8_t* data,
                                    std::size_t len) {
  if (len < 2 || data[0] != 0xFF || data[1] != 0xD8) {
    throw ProtocolError("missing SOI");
  }
  std::vector<Segment> out;
  out.push_back({0xD8, 0, 2});
  std::size_t i = 2;
  while (i + 1 < len) {
    if (data[i] != 0xFF) {
      throw ProtocolError("expected marker at offset " + std::to_string(i));
    }
    const std::uint8_t marker = data[i + 1];
    if (i + 4 > len) {
      throw ProtocolError("truncated segment at offset " + std::to_string(i));
    }
    const std::size_t length =
        (static_cast<std::size_t>(data[i + 2]) << 8) | data[i + 3];
    if (length < 2 || i + 2 + length > len) {
      throw ProtocolError("bad segment length at offset " + std::to_string(i));
    }
    out.push_back({marker, i, length});
    if (marker == 0xDA) return out;
    i += 2 + length;
  }
  throw ProtocolError("no SOS found");
}

